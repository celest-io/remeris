package gitea

import (
	"context"
	"encoding/json"
	"net/http"
	"net/url"
	"strings"
)

const (
	// redactedHost stands for a host that cannot be shown safely.
	redactedHost = "[REDACTED]"
	// createReleaseActivity completes the "while ..." of the errors of the release request.
	createReleaseActivity = "creating a release"
)

// ReleaseInput describes the release to create (spec F16.2).
type ReleaseInput struct {
	// TagName is the tag of the release.
	TagName string
	// Name is the title of the release.
	Name string
	// Body is the release notes, trimmed. Empty asks Gitea to generate the notes.
	Body string
	// Prerelease marks the release as a prerelease.
	Prerelease bool
	// TargetCommitish is the HEAD commit SHA the tag is created from. Empty means unknown: the field is omitted.
	TargetCommitish string
}

// releaseRequest is the JSON body of the request. The field order is the one of Knope's CreateReleaseInput, and a
// struct (not a map) keeps it that way.
type releaseRequest struct {
	TagName string `json:"tag_name"`
	Name    string `json:"name"`
	Body    string `json:"body,omitempty"`
	// Prerelease marks a prerelease.
	Prerelease bool `json:"prerelease"`
	// GenerateReleaseNotes is true when there is no body.
	GenerateReleaseNotes bool `json:"generate_release_notes"`
	// Draft is always false: releases are published at once.
	Draft           bool   `json:"draft"`
	TargetCommitish string `json:"target_commitish,omitempty"`
}

// CreateRelease creates the release, published at once. Gitea creates the tag from target_commitish when it does not
// exist. Call it only in a real run.
//
// Unlike Knope, which requires the response to hold `url` and `upload_url`, any valid JSON is accepted: older
// versions of Gitea have no `upload_url`, and the response is not used.
func (c *Client) CreateRelease(ctx context.Context, in ReleaseInput) error {
	req := releaseRequest{
		TagName:              in.TagName,
		Name:                 in.Name,
		Body:                 in.Body,
		Prerelease:           in.Prerelease,
		GenerateReleaseNotes: in.Body == "",
		TargetCommitish:      in.TargetCommitish,
	}
	var ignored json.RawMessage
	return c.do(ctx, http.MethodPost, c.cfg.releasesURL(), nil, req, &ignored, createReleaseActivity)
}

// DescribeRelease returns the line of a dry run (spec F16.2). Nothing is sent and no client is needed. The line may
// hold line breaks (the notes). The host is printed as written, except that a user name and password in it are
// removed: see [DisplayHost].
func DescribeRelease(cfg Config, in ReleaseInput) string {
	kind := "release"
	if in.Prerelease {
		kind = "prerelease"
	}
	body := "autogenerated body"
	if in.Body != "" {
		body = "body:\n" + in.Body
	}
	target := ""
	if in.TargetCommitish != "" {
		target = " at commit " + in.TargetCommitish
	}
	return "Would create a " + kind + " on Gitea [" + DisplayHost(cfg.Host) + "] with name " + in.Name + " and tag " +
		in.TagName + target + " and " + body
}

// DisplayHost returns host as it can be printed in a dry run, where the host is not checked: as written, unless it
// holds a user name or a password, which are removed. A host that contains "@" and cannot be parsed as a URL with a
// host is replaced by a placeholder, since a password could be anywhere in it.
func DisplayHost(host string) string {
	if !strings.Contains(host, "@") {
		return host
	}
	u, err := url.Parse(host)
	if err != nil || u.User == nil || u.Host == "" {
		return redactedHost
	}
	u.User = nil
	return u.String()
}
